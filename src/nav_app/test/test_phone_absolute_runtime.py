class CompletedQueue(Queue):
    def __init__(self,*outputs):super().__init__();self.outputs=list(outputs)
    def poll(self,wait=False):return self.outputs.pop(0) if self.outputs else None


def test_qualified_window_waits_for_current_pose_instead_of_losing_async_result():
    s,now,r,c,v=setup();before=copy.deepcopy(s.alignment)
    # A real field result arrived with 1.169s old LiVO, despite belonging to the
    # current session/epoch. Delay is not evidence that the solved window is bad.
    now[0]=105.169;r.worker=CompletedQueue((c,v));r.poll(s)
    assert r.pending_position==(c,v) and r.pending_waiting_pose
    assert r.completed[-1]['consumer_pending'] and not r.completed[-1]['consumer_accepted']
    assert s.alignment==before and s.trial.phone_translation.target is None
    assert r.accepted==r.rejected==0
    for _ in range(3):r.poll(s)
    assert r.pending_position==(c,v) and len(r.completed)==1
    s.feed_odom(105.,[5.,0.,0.],[0.,0.,0.,1.]);r.poll(s)
    assert r.pending_position is None and r.accepted==1
    assert r.completed[-1]['consumer_retried'] and r.completed[-1]['consumer_accepted']
    assert s.alignment['absolute_anchor_stamp']==101.
    assert s.trial.phone_translation.target['odom']==[1.,0.,0.]
    revision=r.revision;r.poll(s)
    assert r.revision==revision


