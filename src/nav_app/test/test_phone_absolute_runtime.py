def test_worker_deadline_and_close_reap_only_owned_child_promptly():
    import time
    queue=AbsoluteQueue(child_target=worker_probe,deadline_seconds=.2)
    queue.submit({'sleep':10},{})
    started=time.monotonic()
    assert queue.poll(wait=True)[1]['reason']=='worker_deadline_exceeded'
    assert time.monotonic()-started<1.5
    queue.submit({'sleep':10},{})
    started=time.monotonic();queue.close()
    assert time.monotonic()-started<1.5 and queue.future is None


def test_spawn_failure_is_reported_and_next_window_can_retry(monkeypatch):
    import nav_app.phone_absolute_runtime as module
    queue=AbsoluteQueue(child_target=worker_probe)
    real=module.multiprocessing.get_context
    def unavailable(*args):raise OSError('process budget')
    monkeypatch.setattr(module.multiprocessing,'get_context',unavailable)
    queue.submit({},{});assert 'worker_unavailable' in queue.poll()[1]['reason']
    monkeypatch.setattr(module.multiprocessing,'get_context',real)
    queue.submit({'token':3},{});assert queue.poll(wait=True)[1]['token']==3
    queue.close()
