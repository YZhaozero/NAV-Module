def test_heading_position_scale_uses_net_displacement_and_not_geographic_translation():
    s,now=fixture();s.alignment.update(absolute_anchor_stamp=104.,yaw_sigma_rad=math.radians(7))
    s._anchor_odometry();base=s.odom_distance
    for i in range(1,2001):
        stamp=104.+i*.1;now[0]=stamp+.01
        x=4.+min(i,2000-i)*.1
        s.feed_odom(stamp,[x,0.,0.],[0.,0.,0.,1.])
        p=s._position_now()
        if i==1000:
            assert p['yaw_displacement_sigma_m']==pytest.approx(100*math.radians(7))
            assert p['distance_since_correction_m']==pytest.approx(100.)
            s.alignment['tx']+=10.
            # This test isolates uncertainty propagation; ordinary position
            # arbitration quite correctly rejects a naked 10m pose jump.
            s.previous_output=None
            assert s._position_now()['yaw_displacement_sigma_m']==p['yaw_displacement_sigma_m']
    p=s._position_now()
    assert p['yaw_displacement_sigma_m']==pytest.approx(0.)
    assert p['distance_since_correction_m']==pytest.approx(200.)
    assert s.odom_distance-base==pytest.approx(200.)


