class Queue:
    def __init__(self):self.future=None;self.pending=None;self.requests=[]
    def submit(self,snapshot,context):self.requests.append((snapshot,context));self.future=True
    def clear_pending(self):self.pending=None
    def close(self):pass
    def poll(self,wait=False):return None


